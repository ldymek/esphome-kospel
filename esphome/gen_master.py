def swap_signed(scale, fault):
    l=["- lambda: |-",
       "          uint16_t v=(uint16_t)x; v=((v&0xFF)<<8)|(v>>8); int16_t s=(int16_t)v;"]
    if fault: l.append("          if (s <= -1000) return NAN;")
    l.append(f"          return s * {float(scale)}f;")   # float() so scale=1 -> 1.0f (valid literal)
    return "\n        ".join(l)
def swap_uint():
    return "- lambda: |-\n          uint16_t v=(uint16_t)x; return ((v&0xFF)<<8)|(v>>8);"

