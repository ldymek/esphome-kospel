def bit_rmw(setbit, bit=8, reg=0x0B55, dev="heater", arm=""):
    op=f"real |= (1<<{bit});" if setbit else f"real &= ~(1<<{bit});"
    return f'''- lambda: |-
          if(!id(esp_owns_bus)){{return;}}
          {arm}
          auto rd=esphome::modbus_controller::ModbusCommandItem::create_read_command(
              id({dev}), esphome::modbus_controller::ModbusRegisterType::HOLDING, 0x{reg:04X}, 1,
              [](esphome::modbus::EntityType, uint16_t, std::span<const uint8_t> d) {{
                if (d.size()<2) return;
                uint16_t real=(uint16_t)((d[1]<<8)|d[0]); {op}
                uint16_t gw=((real&0xFF)<<8)|(real>>8);
                id({dev})->queue_command(esphome::modbus_controller::ModbusCommandItem::create_write_multiple_command(
                    id({dev}), 0x{reg:04X}, 1, {{gw}}));
              }});
          id({dev})->queue_command(rd);'''

