# ---------- write pending/confirm framework ----------
# A user-set control ARMs a pending slot (target + deadline). Readback syncs are GUARDED:
# while pending, a non-matching device value is suppressed (control keeps the new position);
# a matching value confirms (slot cleared); past the deadline the control reverts to the device
# value and the slot is marked failed (surfaced via the "Zapisy nieudane" text sensor, auto-clear
# 10 min). Guards compare in engineering units; selects/switches compare by index/bool as float.
WP_TIMEOUT_MS = 90000   # heater applies 0x0B55-gated config with up to ~30 s lag + poll cycle
WP = []      # (entity_id, display_name)
WPIDX = {}   # entity_id -> slot index
WP_EPS = {}  # entity_id -> compare tolerance
def wp_reg(ent, name, eps=0.1):
    if ent in WPIDX: return WPIDX[ent]
    WPIDX[ent] = len(WP); WP.append((ent, name)); WP_EPS[ent] = eps
    return WPIDX[ent]

def wp_arm(ent, val_expr):
    i = WPIDX[ent]
    return f"id(wp_target)[{i}]=({val_expr}); id(wp_until)[{i}]=millis()+{WP_TIMEOUT_MS}UL; id(wp_failed)[{i}]=0;"

def wp_pub(ent, nv_expr, pub_stmt):
    i = WPIDX[ent]; eps = WP_EPS[ent]
    return (f"{{ float nv=({nv_expr}); if(id(wp_until)[{i}]!=0){{ "
            f"if(fabsf(nv-id(wp_target)[{i}])<={eps:g}f){{ id(wp_until)[{i}]=0; {pub_stmt} }} "
            f"else if(millis()>id(wp_until)[{i}]){{ id(wp_until)[{i}]=0; id(wp_failed)[{i}]=millis(); {pub_stmt} }} "
            f"}} else {{ {pub_stmt} }} }}")

